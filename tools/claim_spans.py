#!/usr/bin/env python3
"""Claim-to-span review sheet (Water Advisor session 7). Stdlib only.

For each page file given, resolve every claim's supporting quotes against the
CAPTURED source files (never live eCFR), recheck the capture digest and the
span hash, and print a markdown sheet: per claim, its id, kind, subject, value,
unit, conditions, exceptions and applicability, then each supporting quote's
verbatim captured text with its capture file and anchor.

Flags (heuristic, for the human reader; the script does not judge meaning):
  FLAG no-quote        a claim with no supporting quote (schema forbids it; belt and braces)
  FLAG unsupported-ref a condition or exception mentions a section reference
                       (e.g. 141.64(b)(2)(iii)) or a bare number (e.g. 0.8) that
                       appears in none of the claim's supporting quote texts

Any anchor that does not resolve, any capture digest or span hash that does not
match, stops the run with exit code 1 and a FAIL line naming the quote.

Usage: claim_spans.py <page.json>... [--out FILE]     (markdown to stdout or FILE)
       claim_spans.py --selftest
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import answer_path  # noqa: E402  (capture_path_for, sha256)
import quote_tool   # noqa: E402  (normalized_text, span_hash)

REGISTRY = ROOT / "sources" / "source-registry.dbp-first-proof.json"
SECTION_REF = re.compile(r"\b1\d\d\.\d+(?:\([a-z0-9]+\))*")
NUMBER = re.compile(r"(?<![A-Za-z0-9.,/-])\d+(?:[.,]\d+)*(?![A-Za-z0-9/-])")  # not pieces of dates, document IDs or ratios
GENERIC_NUMBERS = {"1", "2", "3", "4", "5"}  # ordinal-ish counts ("three samples") are not evidence claims


def load_registry():
    reg = json.load(open(REGISTRY, encoding="utf-8"))
    return {s["source_id"]: s for s in reg["sources"]}


def resolve_quotes(page, reg, texts):
    """quote_id -> {text, file, anchor}; raises SystemExit on any resolution or hash failure."""
    out = {}
    for q in page["quotes"]:
        src = reg.get(q["source_id"])
        if not src:
            sys.exit(f"FAIL {q['quote_id']}: source {q['source_id']} not in registry")
        cpath, cite = answer_path.capture_path_for(src)
        if not cpath or not cpath.exists():
            sys.exit(f"FAIL {q['quote_id']}: capture file missing for {q['source_id']}")
        if answer_path.sha256(cpath.read_bytes()) != q["captured_source_sha256"]:
            sys.exit(f"FAIL {q['quote_id']}: capture digest mismatch for {cpath.name}")
        if cpath not in texts:
            texts[cpath] = quote_tool.normalized_text(str(cpath))
        m = re.match(r"^normalized:(\d+)-(\d+)$", q["anchor"]["value"])
        if not m:
            sys.exit(f"FAIL {q['quote_id']}: bad anchor {q['anchor']['value']}")
        a, b = int(m.group(1)), int(m.group(2))
        span = texts[cpath][a:b]
        if a >= b or b > len(texts[cpath]) or quote_tool.span_hash(span) != q["span_sha256"]:
            sys.exit(f"FAIL {q['quote_id']}: span hash mismatch at {q['anchor']['value']} in {cpath.name}")
        out[q["quote_id"]] = {"text": span, "file": str(cpath.relative_to(ROOT)), "anchor": q["anchor"]["value"], "cite": cite}
    return out


def refs_and_numbers(text):
    refs = set(SECTION_REF.findall(text))
    stripped = SECTION_REF.sub(" ", text)  # a section number is a reference, not a value
    nums = {n for n in NUMBER.findall(stripped) if n not in GENERIC_NUMBERS}
    return refs, nums


def flags_for(claim, quotes):
    flags = []
    qids = claim.get("supporting_quote_ids") or []
    if not qids:
        flags.append("no-quote")
    # a quote's own section (its cite) counts as present: a condition citing the quoted section is supported by it
    joined = " ".join(quotes[q]["text"] + " " + quotes[q]["cite"] for q in qids if q in quotes)
    jrefs, jnums = refs_and_numbers(joined)
    # section numbers quoted without paragraph letters still cover a paragraph reference to the same section
    jsections = {r.split("(")[0] for r in jrefs}
    for kind in ("conditions", "exceptions"):
        for item in claim.get(kind) or []:
            refs, nums = refs_and_numbers(item)
            missing_refs = sorted(r for r in refs if r not in jrefs and r.split("(")[0] not in jsections)
            missing_nums = sorted(n for n in nums if n not in jnums and n.replace(",", "") not in {x.replace(",", "") for x in jnums})
            if missing_refs or missing_nums:
                flags.append(f"unsupported-ref ({kind[:-1]}: {', '.join(missing_refs + missing_nums)}): {item}")
    return flags


def render(pages_paths):
    reg = load_registry()
    texts = {}
    lines, totals = [], {"pages": 0, "claims": 0, "quotes": 0, "flags": 0}
    lines.append("# Claim-to-span review sheet\n")
    lines.append("Generated by `tools/claim_spans.py` from the CAPTURED sources (eCFR point-in-time 2026-07-01, normalized under dw-quote-normalization/v0.1). Every quote below was re-resolved from its capture file and its span hash and capture digest rechecked before printing. Flags are lexical heuristics for the reader, not verdicts.\n")
    for path in pages_paths:
        page = json.load(open(path, encoding="utf-8"))
        quotes = resolve_quotes(page, reg, texts)
        totals["pages"] += 1; totals["quotes"] += len(quotes)
        lines.append(f"\n## {page['page_id']} ({page['status']}): {page['title']}\n")
        lines.append(f"Page applicability: system types {', '.join(page['applicability']['system_types'])}; conditions: " + " | ".join(page["applicability"]["conditions"]) + ("; exclusions: " + " | ".join(page["applicability"]["exclusions"]) if page["applicability"]["exclusions"] else "") + "\n")
        for c in page["claims"]:
            totals["claims"] += 1
            fl = flags_for(c, quotes); totals["flags"] += len(fl)
            val = c.get("value"); unit = f" {c['unit']}" if c.get("unit") else ""
            lines.append(f"\n### {c['claim_id']}\n")
            lines.append(f"- kind: {c['kind']}; relation: {c['relation']['operator']} / {c['relation']['regulatory_metric']}")
            lines.append(f"- subject: {c['subject']}")
            lines.append(f"- value: {val}{unit}")
            for kind in ("conditions", "exceptions"):
                items = c.get(kind) or []
                lines.append(f"- {kind}: " + ("none" if not items else ""))
                for it in items:
                    lines.append(f"  - {it}")
            ap = c["applicability"]
            lines.append(f"- applicability: {', '.join(ap['system_types'])}; " + " | ".join(ap["conditions"]) + ("; exclusions: " + " | ".join(ap["exclusions"]) if ap.get("exclusions") else ""))
            for f in fl:
                lines.append(f"- **FLAG {f}**")
            for qid in c["supporting_quote_ids"]:
                q = quotes[qid]
                lines.append(f"- quote `{qid}` ({q['cite']}; `{q['file']}` {q['anchor']}):")
                lines.append(f"  > {q['text']}")
    lines.insert(2, f"Totals: {totals['pages']} pages, {totals['claims']} claims, {totals['quotes']} quotes, {totals['flags']} flags.\n")
    return "\n".join(lines) + "\n", totals


def selftest():
    import copy, tempfile
    results = []
    mclg = ROOT / "pages" / "dbp.mclg.json"
    md, tot = render([mclg])
    results.append(("signed page resolves (12 claims, 2 quotes)", tot["claims"] == 12 and tot["quotes"] == 2))
    # the signed MCLG page carries an unquoted cross-reference ("the MCLs in 141.64 and the MRDLs in 141.65") on
    # every claim, plus the EPA-guide 0.2 value in the TCAA discrepancy note: 13 heuristic flags, by design
    results.append(("signed page's unquoted cross-references are flagged (13)", tot["flags"] == 13 and md.count("141.64, 141.65") == 12 and "0.2" in md))
    results.append(("sheet prints verbatim captured text", "Chlorite 0.8" in md and "quote.dbp.mclg.table" in md))
    page = json.load(open(mclg, encoding="utf-8"))
    bad = copy.deepcopy(page); bad["quotes"][0]["span_sha256"] = "0" * 64
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as f:
        json.dump(bad, f); badpath = f.name
    try:
        render([badpath]); results.append(("tampered span hash stops the run", False))
    except SystemExit as e:
        results.append(("tampered span hash stops the run", "span hash mismatch" in str(e)))
    bad2 = copy.deepcopy(page); bad2["quotes"][0]["anchor"]["value"] = "normalized:999999-1000000"
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as f:
        json.dump(bad2, f); badpath2 = f.name
    try:
        render([badpath2]); results.append(("out-of-range anchor stops the run", False))
    except SystemExit as e:
        results.append(("out-of-range anchor stops the run", "span hash mismatch" in str(e)))
    quotes = {"q1": {"text": "Bromate 0.010 Chlorite 1.0 under § 141.64", "file": "x", "anchor": "a", "cite": "c"}}
    c_ok = {"supporting_quote_ids": ["q1"], "conditions": ["The 141.64(a) table lists bromate (0.010 mg/L) and chlorite (1.0 mg/L)"], "exceptions": []}
    c_bad = {"supporting_quote_ids": ["q1"], "conditions": ["The chlorite MCLG is 0.8 mg/L (141.53)"], "exceptions": []}
    c_none = {"supporting_quote_ids": [], "conditions": [], "exceptions": []}
    results.append(("numbers and section present in quotes: no flag", flags_for(c_ok, quotes) == []))
    fb = flags_for(c_bad, quotes)
    results.append(("number and section absent from quotes: flagged", len(fb) == 1 and "141.53" in fb[0] and "0.8" in fb[0]))
    results.append(("claim with no quote: flagged", any(f == "no-quote" for f in flags_for(c_none, quotes))))
    for name, ok in results:
        print(("PASS " if ok else "FAIL ") + name)
    print(f"{sum(1 for _, o in results if o)}/{len(results)} passed")
    return all(o for _, o in results)


def main(argv):
    if not argv:
        print(__doc__, file=sys.stderr); sys.exit(2)
    if argv[0] == "--selftest":
        sys.exit(0 if selftest() else 1)
    out = None
    if "--out" in argv:
        i = argv.index("--out"); out = Path(argv[i + 1]); argv = argv[:i] + argv[i + 2:]
    md, tot = render(argv)
    if out:
        out.write_text(md, encoding="utf-8")
        print(f"wrote {out}: {tot['pages']} pages, {tot['claims']} claims, {tot['quotes']} quotes, {tot['flags']} flags")
    else:
        sys.stdout.write(md)


if __name__ == "__main__":
    main(sys.argv[1:])
